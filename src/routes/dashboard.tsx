import { createFileRoute } from '@tanstack/react-router'

export const Route = createFileRoute('/dashboard')({
  component: CareerCommandCenter,
})


import { PageHeader } from "@/components/layout/PageHeader";
import { FeatureHeader } from "@/components/shared/FeatureHeader";
import { SectionCard } from "@/components/shared/Cards";
import { HeroSection } from "@/features/dashboard/components/HeroSection";
import { QuickActions } from "@/features/dashboard/components/QuickActions";
import { ChartsPanel } from "@/features/dashboard/components/ChartsPanel";
import { AIActivity } from "@/features/dashboard/components/AIActivity";
import { useCareerScores, useCareerTasks, useApplications, useNotifications, useJobs } from "@/lib/lemma/queries";
import { LoadingState } from "@/components/shared/States";
import { motion } from "framer-motion";
import { SkillBadge, StatusChip } from "@/components/shared/Badges";
import { Button } from "@/components/ui/button";
import { ArrowRight, Sparkles, UploadCloud } from "lucide-react";

function CareerCommandCenter() {
  const { data: scores, isLoading: loadingScores } = useCareerScores();
  const { data: tasks, isLoading: loadingTasks } = useCareerTasks();
  const { data: applications, isLoading: loadingApps } = useApplications();
  const { data: notifications, isLoading: loadingNotifs } = useNotifications();
  const { data: jobs, isLoading: loadingJobs } = useJobs();

  if (loadingScores || loadingTasks || loadingApps || loadingNotifs || loadingJobs) {
    return <LoadingState text="Aggregating your career intelligence..." />;
  }

  return (
    <motion.div 
      initial={{ opacity: 0, y: 20 }}
      animate={{ opacity: 1, y: 0 }}
      className="space-y-6 pb-12 max-w-7xl mx-auto"
    >
      <PageHeader 
        title="Career Command Center" 
        description="Your AI-managed career status at a glance." 
      />

      <FeatureHeader 
        title="Career Intelligence Dashboard"
        description="Aggregates data from all AI agents to show your real-time career readiness, active applications, and prioritized next actions."
        agent="career_planner"
        resources={["career_scores", "resumes table", "jobs table"]}
        estimatedTime="~2s"
      />

      <QuickActions />

      <HeroSection scores={scores} tasks={tasks} jobs={jobs} />

      <div className="grid gap-6 lg:grid-cols-3">
        {/* Left Column */}
        <div className="lg:col-span-2 space-y-6">
          <SectionCard title="AI Recommendations" description="Prioritized actions generated by your AI Career Planner.">
            <div className="space-y-3">
              {tasks && tasks.length > 0 ? (
                tasks.slice(0, 4).map((task: any) => (
                  <div key={task.id || task.title} className="flex items-center justify-between p-3.5 border border-border rounded-xl hover:bg-muted/50 hover:shadow-sm transition-all duration-300">
                    <div className="flex-1 min-w-0">
                      <h4 className="font-medium text-sm text-foreground">{task.title || 'Task'}</h4>
                      <div className="flex items-center gap-2 mt-1">
                        <span className={`text-[10px] font-bold uppercase tracking-wider px-2 py-0.5 rounded-full ${task.priority === 'Critical' ? 'bg-red-500/10 text-red-600 dark:text-red-400' : task.priority === 'High' ? 'bg-amber-500/10 text-amber-600 dark:text-amber-400' : 'bg-muted text-muted-foreground'}`}>
                          {task.priority || 'Normal'}
                        </span>
                        {task.source && (
                          <span className="text-[10px] text-muted-foreground flex items-center gap-1">
                            <Sparkles className="h-2.5 w-2.5" /> {task.source}
                          </span>
                        )}
                      </div>
                    </div>
                    <Button size="sm" variant="secondary" className="rounded-lg shadow-sm shrink-0 ml-3">Start</Button>
                  </div>
                ))
              ) : (
                <div className="text-center py-8 bg-muted/20 rounded-xl border border-dashed border-border">
                  <UploadCloud className="h-8 w-8 mx-auto text-muted-foreground mb-3" />
                  <p className="text-sm font-medium text-foreground">No tasks yet</p>
                  <p className="text-xs text-muted-foreground mt-1">Upload a resume or analyze a job to generate AI recommendations.</p>
                </div>
              )}
            </div>
          </SectionCard>

          <SectionCard title="Skill Gap Analysis" description="Skills your target roles require that are missing from your resume.">
            <div className="flex flex-wrap gap-2 pt-2">
              {jobs && jobs.some((j: any) => j.missing_skills?.length > 0) ? (
                jobs.flatMap((j: any) => j.missing_skills || []).slice(0, 6).map((skill: string, i: number) => (
                  <SkillBadge key={i} skill={skill} className={i < 2 ? "bg-red-500/10 text-red-600 dark:text-red-400 border border-red-500/20" : ""} />
                ))
              ) : (
                <div className="text-sm text-muted-foreground py-4 w-full text-center">Analyze a job description to discover your skill gaps.</div>
              )}
            </div>
          </SectionCard>

          <ChartsPanel applications={applications} />
        </div>

        {/* Right Column */}
        <div className="space-y-6">
          <SectionCard title="Active Applications">
            <div className="space-y-4 pt-2">
              {applications && applications.length > 0 ? (
                applications.slice(0, 5).map((app: any) => (
                  <div key={app.id || app.company} className="flex items-center justify-between">
                    <div>
                      <span className="text-sm font-medium">{app.company || `App ${app.id}`}</span>
                      {app.position && <p className="text-[11px] text-muted-foreground">{app.position}</p>}
                    </div>
                    <StatusChip status={app.status || "Applied"} />
                  </div>
                ))
              ) : (
                <div className="text-sm text-muted-foreground py-4 text-center">No active applications</div>
              )}
              <Button variant="link" className="px-0 h-auto text-sm text-indigo-500">View all <ArrowRight className="h-3 w-3 ml-1" /></Button>
            </div>
          </SectionCard>

          <SectionCard title="AI Activity Timeline" className="h-[400px] overflow-y-auto">
            <AIActivity notifications={notifications} />
          </SectionCard>
        </div>
      </div>
    </motion.div>
  );
}
